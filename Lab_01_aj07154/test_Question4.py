def hashcode(n: int) -> str:
    return hashlib.sha256(str(n).encode('utf-8')).hexdigest()

@pytest.mark.parametrize("n,line,result",question4_testcases)
def test_question4(n,line,result):
    line = line.split()
    for i in range(len(line)):
        line[i] = int(line[i])
    grid = []
    for i in range(n):
        grid.append(line[i*n:(i+1)*n])
    assert hashcode(score(grid,n)) == result